# 误伤豁免：这些词组里出现上面的字串是对的，不算。
EXEMPT = [
    '大人物', '大人家',            # 「大人」也指大人物
    '骑士等级', '骑士阶层',         # equites 的译名，是对的
    '莎草纸', '羊皮纸',            # 罗马的书写material，跟「纸」无关
]

# 现代标记：带这些字样的开局与词条属于现实侧（2026年纽约），整段跳过。
MODERN_RX = re.compile(r'纽约|曼哈顿|手机|电梯|地铁|公寓|美元|电脑|互联网|电话|'
                       r'2026|二〇二六|摄像头|信用卡|航班|出租车|警察局|监控|'
                       r'苏富比|拍卖|发布会|无人机|社交平台|卫星|融资|媒体')

# 「没有马镫」「无砂糖」「罗马没有缠足」这一路是考据，正是要写的，不算穿帮。
# 否定词可能远在一串顿号列表的前头（「没有番茄、玉米、土豆、辣椒、砂糖」），
# 所以往回一直找到句首；也可能落在后头（「江湖词都没有？」），所以往后也看一眼。
NEG_RX = re.compile(r'(没有|没|无|未见|不见|不用|不许|绝不)[\u4e00-\u9fff、／/]{0,30}$')
NEG_AFT_RX = re.compile(r'^[\u4e00-\u9fff、／/]{0,12}(都没有|没有|都不许|不许|一个都不)')
# 「（约二十七公里）」这种括注是给读者的换算，不是正文单位
GLOSS_RX = re.compile(r'[（(]\s*约?[^）)]{0,12}$')

# 禁用表自己要把禁用词写出来才说得清。判断按「这个词所在的那一句」来，不按固定字窗。
META_RX = re.compile(r'禁|不许|不用|不作|写作|改成|改用|一律用|这一路|之类|路后世|即改')
SENT_RX = re.compile(r'[^。！？；\n]*')


def _sentence_at(t, i):
    a = max(t.rfind('。', 0, i), t.rfind('\n', 0, i), t.rfind('；', 0, i),
            t.rfind('！', 0, i), t.rfind('？', 0, i)) + 1
    m = SENT_RX.match(t, i)
    return t[a:m.end() if m else i]


def scan(text):
    hits = []
    t = text
    for ex in EXEMPT:
        t = t.replace(ex, '　' * len(ex))
    for word, alt, why in BAN:
        for m in re.finditer(re.escape(word), t):
            if META_RX.search(_sentence_at(t, m.start())):   # 讲规矩，不是在用
                continue
            head = t[max(0, m.start() - 40):m.start()]
            if (NEG_RX.search(head)                              # 「没有…、…、它」
                    or NEG_AFT_RX.search(t[m.end():m.end() + 20])  # 「它…都没有？」
                    or GLOSS_RX.search(head)):                     # 「（约二十七公里）」
                continue
            a = max(0, m.start() - 14)
            hits.append((word, alt, why, t[a:m.end() + 14].replace('\n', ' ')))
    return hits


def main(argv):
    if argv and argv[0] == '--text':
        hits = scan(argv[1])
        for w, alt, why, ctx in hits:
            print('  × %-8s（%s）→ %s\n      …%s…' % (w, why, alt, ctx))
        print('=>', '干净' if not hits else '%d 处串朝代' % len(hits))
        return 1 if hits else 0

    root = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'data')
    total = 0
    skipped = []

    def report(where, text):
        nonlocal total
        h = scan(text)
        if h:
            total += len(h)
            print('■ %s' % where)
            for w, alt, why, ctx in h:
                print('  × %-8s（%s）→ %s   …%s…' % (w, why, alt, ctx))

    for p in sorted(glob.glob(os.path.join(root, 'openings', '*.md'))):
        txt = io.open(p, encoding='utf-8').read()
        # 开局首行是 JSON 头，里面有 year：正数＝现实侧
        yr = None
        try:
            yr = json.loads(txt.split('\n', 1)[0]).get('year')
        except Exception:
            pass
        if (yr is not None and yr > 0) or MODERN_RX.search(txt[:400]):
            skipped.append(os.path.basename(p) + '（现实侧）')
            continue
        report(os.path.basename(p), txt)

    for p in sorted(glob.glob(os.path.join(root, 'lore', '*.json'))):
        for e in json.load(io.open(p, encoding='utf-8')):
            body = e.get('content', '') + e.get('title', '')
            if MODERN_RX.search(body):
                skipped.append('%s::%s' % (os.path.basename(p), e.get('title', '')[:18]))
                continue
            report('%s :: %s' % (os.path.basename(p), e.get('title', '')[:24]), body)

    mp = os.path.join(root, 'meta.json')
    if os.path.isfile(mp):
        m = json.load(io.open(mp, encoding='utf-8'))
        for k in ('description', 'personality', 'scenario',
                  'system_prompt', 'post_history_instructions'):
            report('meta.json :: %s' % k, str(m.get(k) or ''))

    if skipped:
        print('\n-- 现实侧，未扫（%d 处）--' % len(skipped))
        for s in skipped[:40]:
            print('   %s' % s)
        if len(skipped) > 40:
            print('   …还有 %d 处' % (len(skipped) - 40))
    print('\n禁用词 %d 条 / 串朝代 %d 处' % (len(BAN), total))
    return 0 if total == 0 else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
